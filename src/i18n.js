export const normalizeLang = (l) => (String(l || '').toLowerCase().startsWith('en') ? 'en' : 'de');
export const langFromHeader = (h) => (/^\s*en/i.test(String(h || '')) ? 'en' : 'de');
export const hasKey = (k) => k in T.de;

export function t(lang, key, vars = {}) {
  const s = T[normalizeLang(lang)][key] ?? T.de[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? '')).trim();
}
